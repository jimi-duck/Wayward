import { mkdirSync, writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { SLOTS, type SlotId } from '../src/content/art';
import { allBriefs, AVOID_ALL, CONTINUATION, STYLE } from './art/briefs';
import { continueBrief } from './art/continue';
import { masterBrief } from './art/master';
import { starterBrief } from './art/starter';

// ── the prompts for every picture ─────────────────────────────────────────
// `npm run art:brief` writes docs/art/CHATGPT-BRIEF.md (the one file to give an
// image generator), docs/art/briefs.md (every prompt in full, to copy from) and
// docs/art/briefs.json (to feed a script). Both are made from the game's own
// rows, so run it again after a captain, a card, an ending or a ship is added.

const TITLES: Record<SlotId, string> = {
  captain: 'Captains and Calloway', contact: 'Named contacts', emblem: 'Emblems', ship: 'Ships', place: 'Ports',
  ending: 'Endings', sighting: 'Sightings (Archive)', file: 'The file (Archive)', region: 'Regions',
  fleet: 'Fleet (continuation)', job: 'Jobs (continuation)', phenomenon: 'Phenomena (continuation)',
  gate: 'Gate stations (third run)', planet: 'Planets (third run)', debrief: 'Debrief scenes (third run)', baybanner: 'Refit bay tab banners',
};

test('write the briefs', () => {
  const list = allBriefs();
  mkdirSync('docs/art', { recursive: true });
  writeFileSync('docs/art/briefs.json', JSON.stringify({ style: STYLE, avoid: AVOID_ALL, briefs: list }, null, 2) + '\n');
  const md: string[] = [
    '# Artwork briefs', '',
    'Generated by `npm run art:brief` from the game’s rows. Do not edit; change `tools/art/looks.ts` or the game data and run it again. How to use these: [ART-SLOTS.md](../ART-SLOTS.md).', '',
    `${list.length} pictures (${list.filter((b) => !b.optional).length} wanted, ${list.filter((b) => b.optional).length} optional).`, '',
  ];
  for (const slot of Object.keys(SLOTS) as SlotId[]) {
    const rows = list.filter((b) => b.slot === slot);
    md.push(`## ${TITLES[slot]} (${rows.length})`, '', `Folder \`src/art/${SLOTS[slot].dir}/\` · ${SLOTS[slot].w}×${SLOTS[slot].h}${SLOTS[slot].alpha ? ' · transparent' : ''} · ${SLOTS[slot].shownIn ? `shown in: ${SLOTS[slot].shownIn}` : 'not shown yet'}`, '');
    for (const b of rows) {
      md.push(`### \`${b.file.replace('src/art/', '')}\`${b.optional ? ' (optional)' : ''}`, '', `- Size ${b.size} · ${b.background}`, `- Shown: ${b.where}`, `- From the game: ${b.facts.join(' · ')}`, '', '```text', b.prompt, '', `Avoid: ${b.avoid}`, '```', '');
    }
  }
  writeFileSync('docs/art/briefs.md', md.join('\n'));
  const first = list.filter((b) => !CONTINUATION.includes(b.slot));
  writeFileSync('docs/art/CHATGPT-BRIEF.md', masterBrief(first) + '\n');
  writeFileSync('docs/art/STARTER-15.md', starterBrief(first) + '\n');
  writeFileSync('docs/art/CONTINUE-BRIEF.md', continueBrief(list) + '\n');
});
