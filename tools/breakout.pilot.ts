import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { fly, stratName, type PilotResult, type Strategy } from './pilot';

// ── the Breakout's balance report ─────────────────────────────────────────
// `npm run pilot:breakout` flies the scripted pilot through the Breakout on
// fixed seeds and writes docs/BALANCE-BREAKOUT.md: how often it gets out,
// how long it takes, how much of it is fighting, what the Krail looks like at
// the jump, and what catches the ones who do not. BREAKOUT_RUNS trades
// precision for speed.

const RUNS = Number(process.env.BREAKOUT_RUNS ?? 16);
const MAX = 1200;

const STRATEGIES: Strategy[] = [
  { kind: 'random' },
  { kind: 'focus', branch: 'laser', second: 'defence' },
  { kind: 'focus', branch: 'torpedo', second: 'defence' },
  { kind: 'focus', branch: 'mobility', second: 'laser' },
];

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const mmss = (s: number) => { const r = Math.round(s); return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, '0')}`; };
const pct = (n: number) => `${Math.round(n * 100)}%`;

it('flies the Breakout', { timeout: 3_600_000 }, () => {
  const all: Array<PilotResult & { evade: boolean }> = [];
  const rows: string[] = [];
  for (const strat of STRATEGIES) {
    for (const evade of [false, true]) {
      const res: PilotResult[] = [];
      for (let i = 0; i < RUNS; i++) res.push(fly(2000 + i * 11, strat, { maxTime: MAX, breakout: true, evade }));
      all.push(...res.map((r) => ({ ...r, evade })));
      const out = res.filter((r) => r.run.escaped);
      const caught = res.filter((r) => !r.run.escaped);
      rows.push(`| ${stratName(strat)} | ${evade ? 'run it' : 'fight'} | ${out.length}/${res.length} | ${out.length ? mmss(mean(out.map((r) => r.run.time))) : '—'} | ${caught.length ? mmss(mean(caught.map((r) => r.run.time))) : '—'} | ${pct(mean(res.map((r) => r.combat / Math.max(1, r.run.time))))} | ${mean(res.map((r) => r.run.refit)).toFixed(1)} | ${mean(res.map((r) => r.run.ore)).toFixed(0)} | ${mean(res.map((r) => r.run.krail)).toFixed(0)} | ${mean(res.map((r) => r.run.cut)).toFixed(1)} / ${mean(res.map((r) => r.run.fractured)).toFixed(1)} | ${pct(res.filter((r) => r.run.docked > 0).length / res.length)} | ${mean(res.map((r) => r.run.platesLost)).toFixed(1)} / ${mean(res.map((r) => r.run.platesGained)).toFixed(1)} |`);
    }
  }
  const damage: Record<string, number> = {};
  for (const r of all) for (const [k, v] of Object.entries(r.run.damageBy)) damage[k] = (damage[k] ?? 0) + v;
  const total = Object.values(damage).reduce((a, b) => a + b, 0) || 1;
  const dmgRows = Object.entries(damage).sort((a, b) => b[1] - a[1]).slice(0, 14).map(([k, v]) => `| ${k} | ${v} | ${pct(v / total)} |`);
  const causes: Record<string, number> = {};
  for (const r of all) if (!r.run.escaped) causes[r.run.cause || 'timeout'] = (causes[r.run.cause || 'timeout'] ?? 0) + 1;
  const causeRows = Object.entries(causes).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`);
  const blockade = all.flatMap((r) => r.bossFights);
  const md = `# Breakout balance report

Generated by \`npm run pilot:breakout\`: the scripted pilot flew the Breakout
${all.length} times (${RUNS} seeds per strategy, once fighting the blockade
and once running it), on fixed seeds. It mines with the cutter, docks once
when the hold is nearly full or the hull wants patching, and makes for the
lane mouth once the tank holds the jump. A steady player, not a strong one.

## Escapes

| Strategy | Blockade | Escaped | Time to escape | Lasted, if caught | Time in combat | Refits | Ore | Krail | Cut / fractured | Docked | Plates lost / gained |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

"Time in combat" is the share of the run with a hostile in firing range of
the ship.

## The blockade

| Outcome | Fights |
|---|---|
| killed | ${blockade.filter((b) => b.outcome === 'killed').length} |
| escaped (she left) | ${blockade.filter((b) => b.outcome === 'escaped').length} |
| died | ${blockade.filter((b) => b.outcome === 'died').length} |

## What caught the ones who did not get out

| Cause | Runs |
|---|---|
${causeRows.join('\n')}

## Where the damage comes from

| Source | Hits | Share |
|---|---|---|
${dmgRows.join('\n')}
`;
  writeFileSync(new URL('../docs/BALANCE-BREAKOUT.md', import.meta.url), md);
});
