import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { ARC, SITUATION_BY_ID, SITUATIONS } from '../src/content/situations';
import { REGIONS_LONG } from '../src/content/regions';
import { makeChart, regionOf, sysById } from '../src/sim/chart';
import { endSortie, newJourney, plot, sortieDef } from '../src/sim/journey';
import { laySituations } from '../src/sim/situations';
import { World } from '../src/sim/world';
import { flyWorld, type Strategy } from './pilot';
import { planRoute } from './route';

// ── the situations' balance report ────────────────────────────────────────
// `npm run pilot:situations` writes docs/BALANCE-SITUATIONS.md:
//   1. what the chart deals, region by region: how many situations, how many
//      are the unknown's, how many ships in them are ever hostile
//   2. the first half hour: a scripted pilot flies the first legs of a
//      journey, and the table says what it met, minute by minute
// The pilot does not take the goals (it answers calls by one policy), so
// the table says what is on offer, not how well a person would do.

const SEEDS = Number(process.env.SITUATION_SEEDS ?? 6);
const strat: Strategy = { kind: 'random' };
const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const mmss = (s: number) => { const r = Math.round(s); return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, '0')}`; };

it('reports the situations', { timeout: 3_600_000 }, () => {
  // 1. the chart
  const region: Array<{ n: number; unknown: number; corp: number; front: number; systems: number; quiet: number; actors: number; hostile: number }> = REGIONS_LONG.map(() => ({ n: 0, unknown: 0, corp: 0, front: 0, systems: 0, quiet: 0, actors: 0, hostile: 0 }));
  for (let seed = 1; seed <= 40; seed++) {
    const c = makeChart(seed, 'eight', 0.2);
    const q = laySituations(c, seed);
    for (const s of c.systems) {
      const r = region[regionOf(s)];
      if (!r) continue;
      r.systems++;
      if (s.quiet) r.quiet++;
      const sit = q[s.id];
      if (!sit) continue;
      const d = SITUATION_BY_ID[sit.id]!;
      r.n++;
      if (d.group === 'unknown') r.unknown++; else if (d.group === 'corporate') r.corp++; else r.front++;
      for (const a of d.actors ?? []) { r.actors += a.n; if (a.temper === 'hostile') r.hostile += a.n; }
    }
  }
  const regionRows = region.map((r, i) => `| ${i + 1} ${REGIONS_LONG[i]!.name} | ${(r.n / 40).toFixed(1)} | ${(r.systems / 40).toFixed(1)} | ${Math.round((100 * r.n) / Math.max(1, r.systems))}% | ${Math.round((100 * r.unknown) / Math.max(1, r.n))}% | ${Math.round((100 * r.corp) / Math.max(1, r.n))}% | ${Math.round((100 * r.front) / Math.max(1, r.n))}% | ${Math.round((100 * r.hostile) / Math.max(1, r.actors))}% |`);

  // 2. the first half hour
  const rows: string[] = [];
  const firstUnknown: number[] = [], firstHuman: number[] = [];
  for (let i = 0; i < SEEDS; i++) {
    const seed = 3000 + i * 13;
    const j = newJourney(seed, false, 'eight');
    let at = 0;
    let gotUnknown = false, gotHuman = false;
    const line: string[] = [];
    for (let n = 0; n < 12 && j.status !== 'over'; n++) {
      if (j.status === 'chart') plot(j, planRoute(j));
      const def = sortieDef(j);
      const w = new World(seed * 31 + n * 7 + 1, { mode: 'breakout', sortie: def, carry: j.carry });
      const res = flyWorld(w, seed * 31 + n, strat, { maxTime: 1200, breakout: true, policy: 'bluff' });
      const d = def.situation ? SITUATION_BY_ID[def.situation] : null;
      const met = w.stage && w.stage.begun;
      const t0 = at;
      at += w.runTime;
      if (d && met && d.group === 'unknown' && !gotUnknown) { gotUnknown = true; firstUnknown.push(t0 / 60 + (d.at + 20) / 60); }
      if (d && met && d.group !== 'unknown' && !gotHuman) { gotHuman = true; firstHuman.push(t0 / 60 + (d.at + 20) / 60); }
      line.push(`${mmss(t0)} ${def.kind}${d ? ` · ${d.name}${met ? '' : ' (not reached)'}` : ''}`);
      if (w.phase !== 'over') break;
      endSortie(j, w.result());
      void res;
    }
    rows.push(`| ${seed} | ${line.join('<br>')} |`);
  }

  const md = `# Situations balance report

Generated by \`npm run pilot:situations\`. A first guess at the numbers, from
the scripted pilot; a person flies slower and takes more of what is offered.

## What the chart deals

Forty charts of the eight-region journey. "Share" is the share of systems
with a situation; the three after it are the shares of those that belong to
the unknown, the corporate story and the frontier. "Hostile" is the share of
the ships standing in them whose temper is hostile from the start (none: the
rest turn only on a reason).

| Region | Situations | Systems | Share | Unknown | Corporate | Frontier | Hostile |
|---|---|---|---|---|---|---|---|
${regionRows.join('\n')}

## The first half hour

The first ${12} systems of ${SEEDS} journeys, with the minute the pilot arrived and what the
system had going on. The first alien moment comes on average at minute
${mean(firstUnknown).toFixed(0)} (${firstUnknown.length} of ${SEEDS} journeys); the first human optional situation at
minute ${mean(firstHuman).toFixed(0)} (${firstHuman.length} of ${SEEDS}).

| Seed | Systems, by arrival |
|---|---|
${rows.join('\n')}

${SITUATIONS.length} situations are written; ${ARC.length} sit on the timetable.
`;
  writeFileSync(new URL('../docs/BALANCE-SITUATIONS.md', import.meta.url), md);
});
