import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { EXPANSES, FEATURES, FEATURE_ORDER } from '../src/content/features';
import { reports, Space, weightAt } from '../src/sim/space';
import { Rng } from '../src/sim/rng';

// ── the environment's exposure report ─────────────────────────────────────
// `npm run pilot:space` flies a ship through the composer alone (no hostiles,
// no rock) and writes docs/BALANCE-SPACE.md: how much of a run is spent in
// something, how long the empty stretches are, how the expanses follow one
// another. The scripted pilot of `npm run pilot` hovers near the start, so it
// never reaches a feature; this one flies, as a player does. Two flights: a
// straight run, and a wanderer that turns about every ten seconds.
// SPACE_RUNS and SPACE_MIN trade precision for speed.

const RUNS = Number(process.env.SPACE_RUNS ?? 40);
const MINUTES = Number(process.env.SPACE_MIN ?? 15);
const SPEED = 32;
const DT = 0.1;

interface Flight {
  inside: number; reported: number; busy: number; crowd: number; longestEmpty: number; swaps: number;
  met: Map<string, number>; byExpanse: Map<string, number>; calmFirst: boolean; hardRep: number;
}

function fly(seed: number, wander: boolean): Flight {
  const space = new Space(seed, { hazard: 1 });
  const rng = new Rng(seed * 31 + 7);
  const ship = { x: 0, z: 0, heading: rng.range(0, Math.PI * 2) };
  const f: Flight = { inside: 0, reported: 0, busy: 0, crowd: 0, longestEmpty: 0, swaps: 0, met: new Map(), byExpanse: new Map(), calmFirst: true, hardRep: 0 };
  const seen = new Set<number>();
  let t = 0, turnT = 0, turn = 0, empty = 0, last = '', steps = 0;
  const total = MINUTES * 60;
  while (t < total) {
    if (wander && (turnT -= DT) <= 0) { turnT = rng.range(6, 14); turn = rng.range(-0.08, 0.08); }
    if (wander) ship.heading += turn * DT;
    ship.x += Math.cos(ship.heading) * SPEED * DT; ship.z -= Math.sin(ship.heading) * SPEED * DT;
    t += DT; steps++;
    space.step(DT, t, ship);
    const a = space.sample(ship.x, ship.z);
    const here = a.from.filter((q) => weightAt(q, ship.x, ship.z) * q.level > 0.3);
    if (a.weight > 0.3) f.inside++;
    if (reports(a).length) f.reported++;
    if (a.from.length >= 3) f.crowd++;
    if (a.expanse && EXPANSES[a.expanse.def].load === 'busy') f.busy++;
    if (a.expanse) f.byExpanse.set(a.expanse.def, (f.byExpanse.get(a.expanse.def) ?? 0) + DT);
    for (const q of here) if (!seen.has(q.n)) { seen.add(q.n); f.met.set(q.def, (f.met.get(q.def) ?? 0) + 1); }
    const key = a.expanse ? String(a.expanse.n) : '';
    if (key !== last) { if (last) f.swaps++; last = key; }
    // an empty stretch: no feature within sight (a far one counts as sight)
    const near = space.features.some((q) => FEATURES[q.def].layer === 'far' || Math.hypot(q.x - ship.x, q.z - ship.z) < q.r + 500);
    if (near) empty = 0; else { empty += DT; f.longestEmpty = Math.max(f.longestEmpty, empty); }
    if (t <= 60 && a.expanse && EXPANSES[a.expanse.def].load === 'busy') f.calmFirst = false;
  }
  return f;
}

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const pct = (n: number) => `${Math.round(n * 100)}%`;
const sec = (s: number) => `${Math.round(s)} s`;

it('flies the composer', { timeout: 600_000 }, () => {
  const total = MINUTES * 60 / DT;
  const rows: string[] = [];
  const mets: Record<string, number[]> = {};
  const exps: Record<string, number[]> = {};
  for (const [name, wander] of [['Straight', false], ['Wanderer', true]] as const) {
    const fl: Flight[] = [];
    for (let i = 0; i < RUNS; i++) fl.push(fly(100 + i * 13, wander));
    rows.push(`| ${name} | ${pct(mean(fl.map((x) => x.inside / total)))} | ${pct(mean(fl.map((x) => x.reported / total)))} | ${pct(mean(fl.map((x) => x.busy / total)))} | ${pct(mean(fl.map((x) => x.crowd / total)))} | ${sec(mean(fl.map((x) => x.longestEmpty)))} | ${sec(Math.max(...fl.map((x) => x.longestEmpty)))} | ${(mean(fl.map((x) => x.swaps)) / MINUTES).toFixed(1)} | ${pct(fl.filter((x) => x.calmFirst).length / fl.length)} |`);
    for (const x of fl) {
      for (const id of FEATURE_ORDER) (mets[`${name}|${id}`] ??= []).push(x.met.get(id) ?? 0);
      for (const [id, s] of x.byExpanse) (exps[`${name}|${id}`] ??= []).push(s);
    }
  }
  const featureRows = FEATURE_ORDER.map((id) => `| ${FEATURES[id].name} | ${mean(mets[`Straight|${id}`]!).toFixed(1)} | ${mean(mets[`Wanderer|${id}`]!).toFixed(1)} |`);
  const expRows = Object.keys(EXPANSES).map((id) => `| ${EXPANSES[id as keyof typeof EXPANSES].name} | ${pct(sum(exps[`Straight|${id}`] ?? []) / (RUNS * MINUTES * 60))} | ${pct(sum(exps[`Wanderer|${id}`] ?? []) / (RUNS * MINUTES * 60))} |`);
  const md = `# Environment exposure report

Generated by \`npm run pilot:space\`: a ship flown through the composer alone
(no hostiles, no rock) at ${SPEED} units a second for ${MINUTES} minutes, on
${RUNS} seeds per flight. The scripted pilot of \`npm run pilot\` hovers near
the start and never reaches a feature, so this is the report for the sky.
Same seeds every time.

## Time in the world

"In something" is the share of the flight inside a feature's body (weight over
0.3). "Told" is the share the HUD has a teal condition line. "In a busy
expanse" and "crowd" (three or more features at one point) are the load.
"Empty" is the stretch with no feature in sight (a far one counts), mean of
each flight's longest and the longest of all. "Calm start" is the share of
flights with no busy expanse in the first minute.

| Flight | In something | Told | In a busy expanse | Crowd | Longest empty (mean) | Longest empty (worst) | Expanses a minute | Calm start |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Features met a flight

Distinct features flown into, mean of a ${MINUTES}-minute flight.

| Feature | Straight | Wanderer |
|---|---|---|
${featureRows.join('\n')}

## Time by expanse

| Expanse | Straight | Wanderer |
|---|---|---|
${expRows.join('\n')}
`;
  writeFileSync('docs/BALANCE-SPACE.md', md);
});

function sum(a: number[]) { return a.reduce((x, y) => x + y, 0); }
