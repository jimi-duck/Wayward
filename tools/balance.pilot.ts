import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { fly, stratName, type PilotResult, type Strategy } from './pilot';

// ── the balance report ────────────────────────────────────────────────────
// `npm run pilot` flies the scripted pilot through many seeded runs per
// build strategy and writes docs/BALANCE.md. Same seeds every time, so two
// reports differ only where the game did. PILOT_RUNS and PILOT_TIME
// (environment) trade precision for speed.

const RUNS = Number(process.env.PILOT_RUNS ?? 12);
const MAX = Number(process.env.PILOT_TIME ?? 900);
const UNLOCKED = (process.env.PILOT_UNLOCKED ?? '').split(',').filter(Boolean);

const STRATEGIES: Strategy[] = [
  { kind: 'random' },
  { kind: 'focus', branch: 'laser', second: 'defence' },
  { kind: 'focus', branch: 'torpedo', second: 'laser' },
  { kind: 'focus', branch: 'mine', second: 'mobility' },
  { kind: 'focus', branch: 'close', second: 'defence' },
  { kind: 'focus', branch: 'close', second: 'laser' },
  { kind: 'focus', branch: 'torpedo', second: 'defence' },
  { kind: 'focus', branch: 'plasma', second: 'mobility' },
  { kind: 'focus', branch: 'defence', second: 'laser' },
  { kind: 'focus', branch: 'mobility', second: 'overcharge' },
];

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const q = (a: number[], p: number) => { const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))] ?? 0; };
const mmss = (s: number) => { const r = Math.round(s); return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, '0')}`; };
const pct = (n: number) => `${Math.round(n * 100)}%`;

it('flies the balance matrix', { timeout: 3_600_000 }, () => {
  const all: PilotResult[] = [];
  const rows: string[] = [];
  const t0 = Date.now();
  for (const strat of STRATEGIES) {
    const res: PilotResult[] = [];
    for (let i = 0; i < RUNS; i++) res.push(fly(1000 + i * 7, strat, { maxTime: MAX, unlocked: UNLOCKED }));
    all.push(...res);
    const times = res.map((r) => r.run.time);
    const lost = mean(res.map((r) => r.run.platesLost)), gained = mean(res.map((r) => r.run.platesGained));
    const bosses = res.flatMap((r) => r.bossFights);
    const killed = bosses.filter((b) => b.outcome === 'killed');
    rows.push(`| ${stratName(strat)} | ${mmss(mean(times))} | ${mmss(q(times, 0.25))}–${mmss(q(times, 0.75))} | ${mean(res.map((r) => r.run.refit)).toFixed(1)} | ${Math.round(mean(res.map((r) => r.run.score))).toLocaleString('en-GB')} | ${lost.toFixed(1)} / ${gained.toFixed(1)} | ${killed.length}/${bosses.length} (${mean(killed.map((b) => b.seconds)).toFixed(0)}s) | ${res.filter((r) => r.run.cause === 'survived').length}/${res.length} |`);
  }

  // where the damage comes from, and when
  const damage: Record<string, number> = {};
  for (const r of all) for (const [k, v] of Object.entries(r.run.damageBy)) damage[k] = (damage[k] ?? 0) + v;
  const dmgTotal = Object.values(damage).reduce((a, b) => a + b, 0) || 1;
  const dmgRows = Object.entries(damage).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} | ${pct(v / dmgTotal)} |`);
  const minutes = Math.max(...all.map((r) => r.lostByMinute.length));
  const perMin: string[] = [];
  for (let m = 0; m < minutes; m++) {
    const alive = all.filter((r) => r.run.time >= m * 60);
    if (alive.length < 3) break;
    perMin.push(`| ${m}–${m + 1} | ${alive.length} | ${mean(alive.map((r) => r.lostByMinute[m] ?? 0)).toFixed(2)} | ${mean(alive.map((r) => r.gainedByMinute[m] ?? 0)).toFixed(2)} |`);
  }
  const kills: Record<string, number> = {};
  for (const r of all) for (const [k, v] of Object.entries(r.run.killsBy)) kills[k] = (kills[k] ?? 0) + v;
  const killTotal = Object.values(kills).reduce((a, b) => a + b, 0) || 1;
  const refitAt = (n: number) => mean(all.map((r) => r.refitAt[n]).filter((v): v is number => v !== undefined));
  const fights = all.flatMap((r) => r.bossFights);
  const fightRow = (o: string) => {
    const f = fights.filter((b) => b.outcome === o);
    return `| ${o} | ${f.length} | ${mean(f.map((b) => b.seconds)).toFixed(0)}s | ${pct(mean(f.map((b) => b.hpLeft)))} | ${mean(f.map((b) => b.refit)).toFixed(1)} |`;
  };
  const ids: Record<string, number> = {};
  for (const r of all) ids[r.identity] = (ids[r.identity] ?? 0) + 1;

  const md = `# Balance report

Generated by \`npm run pilot\`: the scripted pilot (\`tools/pilot.ts\`) flew
${all.length} runs, ${RUNS} per strategy, capped at ${mmss(MAX)}, on fixed seeds.
The pilot is competent and unspectacular: it dodges what it can see coming
and shoots what is in front of it, a beat late. Read the numbers as "a
steady player", not as a ceiling.${UNLOCKED.length ? `\n\nUnlocked: ${UNLOCKED.join(', ')}.` : ''}

## By build strategy

| Strategy | Mean survival | Middle half | Refits | Mean score | Plates lost / gained | Capital ships killed (mean fight) | Survived the cap |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Capital-ship fights

| Outcome | Fights | Mean length | Hull left at the end | Refit at the end |
|---|---|---|---|---|
${fightRow('killed')}
${fightRow('escaped')}
${fightRow('died')}

## Where the damage comes from

Plates and shield charges lost, by source, across every run.

| Source | Hits | Share |
|---|---|---|
${dmgRows.join('\n')}

## Health over time

Mean plates lost and gained per minute, among the runs still alive in that minute.

| Minute | Runs alive | Lost | Gained |
|---|---|---|---|
${perMin.join('\n')}

## Pacing

Refit 1 at ${mmss(refitAt(1))}, refit 5 at ${mmss(refitAt(5))}, refit 10 at ${mmss(refitAt(10))}, refit 15 at ${mmss(refitAt(15))} (mean, of runs that got there).

Kills by weapon: ${Object.entries(kills).filter(([, v]) => v > 0).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${pct(v / killTotal)}`).join(' · ')}.

Ships built: ${Object.entries(ids).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} (${v})`).join(' · ')}.
`;
  writeFileSync(new URL('../docs/BALANCE.md', import.meta.url), md);
  console.log(md);
  console.log(`flown in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
});
