import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { MISSIONS } from '../src/content/missions';
import { REGIONS_LONG } from '../src/content/regions';
import { makeChart, regionOf, sysById } from '../src/sim/chart';
import { endSortie, newJourney, plot, sortieDef } from '../src/sim/journey';
import { laySituations } from '../src/sim/situations';
import { World } from '../src/sim/world';
import { flyWorld } from './pilot';
import { planRoute } from './route';

// ── the jobs' report ──────────────────────────────────────────────────────
// `npm run pilot:jobs` writes docs/BALANCE-JOBS.md:
//   1. what the chart deals: jobs per region, and the column of the first one
//   2. what the scripted pilot meets on a whole journey: the jobs it was offered, region by region
// The pilot answers calls by one policy and never takes a goal, so the table says what is on offer.

const SEEDS = Number(process.env.JOB_SEEDS ?? 4);
const ids = new Set(MISSIONS.map((m) => m.id));
const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);

it('reports the jobs', { timeout: 3_600_000 }, () => {
  const N = 40, dealt = Array(8).fill(0) as number[], first: number[] = [];
  for (let seed = 1; seed <= N; seed++) {
    const c = makeChart(seed, 'eight', 0.2);
    const q = laySituations(c, seed);
    let f = 99;
    for (const s of c.systems) if (ids.has(q[s.id]?.id ?? '')) { dealt[regionOf(s)]!++; f = Math.min(f, s.col); }
    first.push(f);
  }

  const offered = Array(8).fill(0) as number[], stops = Array(8).fill(0) as number[];
  let firstStop = 0, firstN = 0;
  const rang: number[] = [];
  for (let i = 0; i < SEEDS; i++) {
    const seed = 5000 + i * 17;
    const j = newJourney(seed, false, 'eight');
    let seen = false;
    for (let n = 0; n < 120 && j.status !== 'over'; n++) {
      if (j.status === 'chart') plot(j, planRoute(j));
      const def = sortieDef(j);
      const region = regionOf(sysById(j.chart, def.system));
      const w = new World(seed * 31 + n * 7 + 1, { mode: 'breakout', sortie: def, carry: j.carry });
      flyWorld(w, seed * 31 + n, { kind: 'random' }, { maxTime: 1200, breakout: true, policy: 'bluff' });
      if (def.system !== j.chart.home) stops[region]!++;
      if (w.stage?.offered && ids.has(w.stage.def.id)) {
        offered[region]!++;
        if (w.stage.rangAt !== null) rang.push(w.stage.rangAt);
        if (!seen) { seen = true; firstStop += n; firstN++; }
      }
      if (w.phase !== 'over') break;
      endSortie(j, w.result());
    }
  }

  rang.sort((a, b) => a - b);
  const pct = (p: number) => (rang.length ? rang[Math.min(rang.length - 1, Math.floor(p * rang.length))]!.toFixed(1) : '-');
  const rows = REGIONS_LONG.map((r, i) => `| ${i + 1} ${r.name} | ${(dealt[i]! / N).toFixed(1)} | ${(stops[i]! / SEEDS).toFixed(1)} | ${(offered[i]! / SEEDS).toFixed(1)} |`);
  writeFileSync(new URL('../docs/BALANCE-JOBS.md', import.meta.url), `# Jobs balance report

Generated by \`npm run pilot:jobs\`. Jobs (see [MISSIONS.md](MISSIONS.md)) are dealt
two ways: the timetable (\`JOB_COLS\`: four columns in the first region, six in each
other, a job in every system of the column) and the roll that deals every other
situation. A job rings on arrival. Before the arrival call and the wider timetable
a lane met about 2.5 jobs in ten stops.

## What the chart deals

Forty charts. The first job sits in column ${mean(first).toFixed(1)} on average (the column
after Cerro is 1).

## What the pilot meets

${SEEDS} whole journeys, flown to the end or to a wreck. "Stops" is the systems the pilot
flew in; "offered" is the jobs whose call rang. A person takes a different lane and
more time, so read it as a floor.

| Region | Jobs dealt per chart | Stops | Offered |
|---|---|---|---|
${rows.join('\n')}

Seconds from arrival to the call ringing (${rang.length} offers): median ${pct(0.5)}, 90th percentile ${pct(0.9)}, longest ${pct(1)}.
A call waits for clear sky, never for a long quiet.

The first job was offered at stop ${(firstStop / Math.max(1, firstN)).toFixed(1)} on average (${firstN} of ${SEEDS} journeys).
`);
});
