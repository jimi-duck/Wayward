import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { LEGS } from '../src/content/road';
import { SCRIPT } from '../src/content/script';
import { regionOf, sysById } from '../src/sim/chart';
import { choices } from '../src/sim/endings';
import { endSortie, newJourney, plot, sortieDef, type Journey } from '../src/sim/journey';
import { World } from '../src/sim/world';
import { flyWorld, stratName, type Policy, type Strategy } from './pilot';
import { planRoute } from './route';

// ── the whole road, Cerro to the Threshold ────────────────────────────────
// `npm run pilot:overhaul` flies the authored road end to end with the scripted
// pilot and writes docs/BALANCE-OVERHAUL.md: how many reach the Threshold, the
// minutes a leg, wrecks, which endings were open there, and the two checks the
// story queue must pass on a real flight: no main beat dropped (each main row
// with no condition has played by the end, or is still carried) and no row
// played twice. These are pilot numbers, not playtests. ROAD_RUNS sets seeds.

const RUNS = Number(process.env.ROAD_RUNS ?? 2);
const STRATEGIES: Strategy[] = [{ kind: 'focus', branch: 'torpedo', second: 'defence' }];
const POLICIES: Policy[] = ['run', 'bluff', 'fight'];
const MAX_SORTIES = 90;

interface Run { j: Journey; legTime: number[]; legWrecks: number[]; reached: boolean; stuck: boolean; dropped: string[]; twice: string[]; open: string[]; minutes: number }

function fly(seed: number, strat: Strategy, policy: Policy): Run {
  const j = newJourney(seed, false, 'road');
  const run: Run = { j, legTime: LEGS.map(() => 0), legWrecks: LEGS.map(() => 0), reached: false, stuck: false, dropped: [], twice: [], open: [], minutes: 0 };
  const visited = new Set<string>();
  let n = 0;
  while (j.status !== 'over' && n < MAX_SORTIES) {
    if (j.status === 'chart') plot(j, planRoute(j));
    const def = sortieDef(j);
    const leg = Math.max(0, regionOf(sysById(j.chart, j.at)));
    if (def.script) visited.add(def.script);
    const w = new World(seed * 31 + n * 7 + 1, { mode: 'breakout', sortie: def, carry: j.carry });
    flyWorld(w, seed * 31 + n, strat, { maxTime: 1500, breakout: true, policy });
    if (w.phase !== 'over') { run.stuck = true; break; }
    run.legTime[leg] = (run.legTime[leg] ?? 0) + w.runTime;
    if (!w.alive) run.legWrecks[leg] = (run.legWrecks[leg] ?? 0) + 1;
    endSortie(j, w.result());
    n++;
  }
  run.reached = j.status === 'over' && j.end === 'through';
  run.minutes = run.legTime.reduce((a, b) => a + b, 0) / 60;
  const seen = j.carry.seen ?? [];
  const pending = new Set(j.carry.pending ?? []);
  run.twice = [...new Set(seen.filter((id, i) => seen.indexOf(id) !== i))];
  run.dropped = SCRIPT.filter((r) => r.main && !r.if && visited.has(r.stop) && !seen.includes(r.id) && !pending.has(r.id)).map((r) => r.id);
  if (run.reached) run.open = choices(j).filter((c) => c.open).map((c) => c.def.id);
  return run;
}

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const LEG_NAMES = ['The Reach', 'The Marches', 'The Salvage Belt', 'The Drift Deep', 'The Breaker Yards', 'The Free Ports', 'The Hollows', 'The Last Lanes'];

it('flies the whole road', { timeout: 7_200_000 }, () => {
  const all: Array<Run & { strat: string; policy: Policy }> = [];
  for (const strat of STRATEGIES) for (const policy of POLICIES) for (let i = 0; i < RUNS; i++) all.push({ ...fly(5000 + i * 17, strat, policy), strat: stratName(strat), policy });
  const runRows = all.map((r) => `| ${r.strat} | ${r.policy} | ${r.reached ? 'yes' : r.stuck ? 'stuck' : 'no'} | ${Math.round(r.minutes)} | ${r.j.wrecks} | ${r.open.join(', ') || '—'} | ${r.dropped.join(', ') || 'none'} | ${r.twice.join(', ') || 'none'} |`);
  const legRows = LEG_NAMES.map((nm, i) => `| ${nm} | ${Math.round(mean(all.map((r) => r.legTime[i]! / 60)))} | ${mean(all.map((r) => r.legWrecks[i]!)).toFixed(1)} |`);
  const md = `# The narrative overhaul: whole-road report

Generated by \`npm run pilot:overhaul\`: the scripted pilot flew ${all.length} journeys down the authored road
(${RUNS} ${RUNS === 1 ? 'seed' : 'seeds'} per policy), Cerro to the Threshold, answering every card by one policy. It jumps as soon
as it can, and does not read. Pilot numbers, not playtests.

## Each journey

"Dropped" lists main beats with no condition that never played at a stop the pilot visited (none is the target).
"Twice" lists script rows recorded as played more than once (none is the target).

| Strategy | Policy | Threshold | Minutes | Wrecks | Endings open | Dropped | Twice |
|---|---|---|---|---|---|---|---|
${runRows.join('\n')}

## Leg by leg

| Leg | Minutes (mean) | Wrecks (mean) |
|---|---|---|
${legRows.join('\n')}
`;
  writeFileSync(new URL('../docs/BALANCE-OVERHAUL.md', import.meta.url), md);
});
