import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { ALIEN_TYPES, cloaked } from '../src/sim/enemies';
import { endSortie, newJourney, plot, sortieDef } from '../src/sim/journey';
import type { GameEvent } from '../src/sim/events';
import { World } from '../src/sim/world';
import { flyWorld, type Policy, type Strategy } from './pilot';
import { planRoute } from './route';

// ── the story communications report ───────────────────────────────────────
// `npm run pilot:comms` flies whole eight-region journeys and logs every
// transmission the Story mode makes: when, what weight, and what the player was
// doing as it arrived (fighting, cutting rock, or free). The report says how
// long the player flies between transmissions, how many cut in on a fight or
// on mining, and how the weights split. It writes docs/BALANCE-COMMS.md.
// JOURNEY_RUNS trades precision for speed (default 4).

const RUNS = Number(process.env.JOURNEY_RUNS ?? 4);
const OUT = process.env.COMMS_OUT ?? 'docs/BALANCE-COMMS.md';
const STRAT: Strategy = { kind: 'focus', branch: 'torpedo', second: 'defence' };
const POLICY: Policy = 'bluff';

interface Tx { t: number; id: string; tier: string; busy: 'fight' | 'cut' | 'free'; stopped: boolean }

function fly(seed: number): { tx: Tx[]; total: number; legs: number } {
  const j = newJourney(seed, false, 'eight');
  const tx: Tx[] = [];
  let clock = 0, n = 0;
  while (j.status !== 'over' && n < 140) {
    if (j.status === 'chart') plot(j, planRoute(j));
    const def = sortieDef(j);
    const w = new World(seed * 31 + n * 7 + 1, { mode: 'breakout', sortie: def, carry: j.carry });
    const base = clock;
    const watch = (w: World, evs: readonly GameEvent[]) => {
      for (const e of evs) {
        const ev = e as { type: string; id?: string; tier?: string };
        if (ev.type !== 'comms' && ev.type !== 'call' && ev.type !== 'ping') continue;
        const near = w.aliens.filter((a) => !cloaked(a) && ALIEN_TYPES[a.kind].fire !== 'none' && Math.hypot(a.x - w.ship.x, a.z - w.ship.z) < 70).length;
        const busy = w.command.state === 'fight' || near > 0 ? 'fight' : w.cutting ? 'cut' : 'free';
        const tier = ev.tier ?? (ev.type === 'comms' ? 'major' : ev.type);
        tx.push({ t: base + w.runTime, id: ev.id ?? '', tier, busy, stopped: ev.type === 'comms' });
      }
    };
    const res = flyWorld(w, seed * 31 + n, STRAT, { maxTime: 1200, breakout: true, policy: POLICY, watch });
    if (w.phase !== 'over') break;
    clock += w.runTime;
    endSortie(j, w.result());
    n++;
    void res;
  }
  return { tx, total: clock, legs: n };
}

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const mmss = (s: number) => { const r = Math.round(s); return `${Math.floor(r / 60)}:${String(r % 60).padStart(2, '0')}`; };
const pct = (n: number) => `${Math.round(n * 100)}%`;

it('flies story journeys and logs the transmissions', { timeout: 7_200_000 }, () => {
  const runs = Array.from({ length: RUNS }, (_, i) => fly(3000 + i * 13));
  const all = runs.flatMap((r) => r.tx);
  const hours = runs.reduce((a, r) => a + r.total, 0) / 3600;
  // gaps between every transmission, and between the ones that stop the world (the blocking ones)
  const gaps = (pick: (x: Tx) => boolean) => runs.flatMap((r) => {
    const v = r.tx.filter(pick).map((x) => x.t);
    return v.slice(1).map((t, i) => t - v[i]!);
  });
  const stopGaps = gaps((x) => x.stopped), anyGaps = gaps(() => true);
  const tiers = new Map<string, number>();
  for (const x of all) tiers.set(x.tier, (tiers.get(x.tier) ?? 0) + 1);
  const stops = all.filter((x) => x.stopped);
  const lines = [
    '# Story communications report',
    '',
    `Generated by \`npm run pilot:comms\`: ${RUNS} eight-region journeys, ${hours.toFixed(1)} h of flight, ${mean(runs.map((r) => r.legs)).toFixed(0)} systems a journey.`,
    'The pilot answers every call, so these are the transmissions a steady player would meet.',
    '',
    '| Measure | Value |',
    '| --- | --- |',
    `| Transmissions an hour (all) | ${(all.length / hours).toFixed(1)} |`,
    `| Transmissions an hour that stop the world | ${(stops.length / hours).toFixed(1)} |`,
    `| Mean gap, all | ${mmss(mean(anyGaps))} |`,
    `| Mean gap, stopping | ${mmss(mean(stopGaps))} |`,
    `| Shortest gap, stopping | ${stopGaps.length ? mmss(Math.min(...stopGaps)) : '—'} |`,
    `| Stopping gaps under two minutes | ${pct(stopGaps.filter((g) => g < 120).length / Math.max(1, stopGaps.length))} |`,
    `| Stopping transmissions that cut in on a fight | ${pct(stops.filter((x) => x.busy === 'fight').length / Math.max(1, stops.length))} |`,
    `| Stopping transmissions that cut in on mining | ${pct(stops.filter((x) => x.busy === 'cut').length / Math.max(1, stops.length))} |`,
    `| Any transmission that arrived in a fight | ${pct(all.filter((x) => x.busy === 'fight').length / Math.max(1, all.length))} |`,
    '',
    '| Weight | Count | An hour |',
    '| --- | --- | --- |',
    ...[...tiers.entries()].map(([k, v]) => `| ${k} | ${v} | ${(v / hours).toFixed(1)} |`),
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
  console.log(lines.join('\n'));
});
