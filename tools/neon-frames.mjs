// Neon Glass frames: writes src/styles/neon-frames.css (run `node tools/neon-frames.mjs` after changing a value here).
// Every pop-up has chamfered corners (owner, 23 October 2026), so the rim, its tight glow, the hairline inside and the
// corner brackets are drawn as nine-slice SVG border images instead of a rounded box shadow; corners keep their size
// on any panel and the straight edges stretch. Cuts follow guidelines v6: 14px on panels, 10px on cards and buttons.
import { writeFileSync } from 'node:fs';

const ROLES = {
  cyan: { rim: '#B4E4EE', halo: '40,150,190', base: 'rgba(16,36,48,.66)' },
  ochre: { rim: '#FFDEA0', halo: '210,140,40', base: 'rgba(54,38,12,.62)' },
  red: { rim: '#FFBEB9', halo: '210,60,60', base: 'rgba(56,16,18,.64)' },
};

/** A chamfered box `w`×`h` at (x, y) with cut `c`, offset outward by `d` (negative: inward), as polygon points. */
function shape(x, y, w, h, c, d) {
  const k = c - d * (Math.SQRT2 - 1); // where the offset cut meets the offset edge
  const L = x - d, T = y - d, R = x + w + d, B = y + h + d;
  const p = [[L + k, T], [R - k, T], [R, T + k], [R, B - k], [R - k, B], [L + k, B], [L, B - k], [L, T + k]];
  return p.map(([a, b]) => `${+a.toFixed(2)},${+b.toFixed(2)}`).join(' ');
}

const uri = (svg) => `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`;
const blur = (id, sd) => `<filter id="${id}" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="${sd}"/></filter>`;

/**
 * A panel's outer frame: the rim just outside the box edge, its tight glow (2px at .8, 6px at .35) and, on panels and
 * cards (`arm` above 0), L brackets 8px outside each corner; the owner took them off (23 October 2026). Drawn on the element's own border image, outset `o`.
 */
function frame({ c, o, k, arm, rim, halo, w = 2, a = 0.8, b = 0.35, fill = '' }) {
  const s = o + k, n = 2 * s + 2, box = n - 2 * o;
  const pts = shape(o, o, box, box, c, w / 2);
  const br = arm ? (() => {
    const e = o - 8, f = n - e;
    return `<path d="M${e} ${e + arm}V${e}H${e + arm}M${f - arm} ${e}H${f}V${e + arm}M${e} ${f - arm}V${f}H${e + arm}M${f - arm} ${f}H${f}V${f - arm}" fill="none" stroke="${rim}" stroke-width="2"/>`;
  })() : '';
  const body = [fill].flat().filter(Boolean).map((f) => `<polygon points="${shape(o, o, box, box, c, 0)}" fill="${f}"/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${n}" height="${n}" viewBox="0 0 ${n} ${n}"><defs>${blur('a', w / 2)}${blur('b', w * 1.5)}</defs>`
    + body
    + `<polygon points="${pts}" fill="none" stroke="rgba(${halo},${b})" stroke-width="${w * 3}" filter="url(#b)"/>`
    + `<polygon points="${pts}" fill="none" stroke="rgba(${halo},${a})" stroke-width="${w * 2}" filter="url(#a)"/>`
    + `<polygon points="${pts}" fill="none" stroke="${rim}" stroke-width="${w}" stroke-linejoin="miter"/>`
    + br + '</svg>';
  return { url: uri(svg), slice: s, outset: o };
}

/** The hairline 6px inside the rim, at 35% of the halo: on the glass layer's border image, so it sits above the fill. */
function hairline({ c, k, halo }) {
  const n = 2 * k + 2;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${n}" height="${n}" viewBox="0 0 ${n} ${n}">`
    + `<polygon points="${shape(0, 0, n, n, c, -6.5)}" fill="none" stroke="rgba(${halo},.35)" stroke-width="1"/></svg>`;
  return { url: uri(svg), slice: k };
}

const PANEL = { c: 14, o: 12, k: 24, arm: 0 };
const CARD = { c: 10, o: 12, k: 20, arm: 0 };
const NEST = { c: 10, o: 6, k: 12, arm: 0, w: 1.5 };
// nested glass fills: the role's dark glass, then its tint when marked or pressed
const FILL = ROLES.cyan.base;
const tint = (halo, x) => `rgba(${halo},${x})`;

const out = [
  '/* Generated by tools/neon-frames.mjs: chamfered Neon Glass frames (rim, tight glow, hairline, brackets). Do not edit. */',
  ':root {',
];
for (const [role, { rim, halo, base }] of Object.entries(ROLES)) {
  const p = frame({ ...PANEL, rim, halo }), q = frame({ ...CARD, rim, halo });
  const ph = hairline({ c: PANEL.c, k: 24, halo }), qh = hairline({ c: CARD.c, k: 20, halo });
  out.push(`  --ngf-panel-${role}: ${p.url};`, `  --ngf-card-${role}: ${q.url};`, `  --ngh-panel-${role}: ${ph.url};`, `  --ngh-card-${role}: ${qh.url};`);
  out.push(`  --ngn-${role}: ${frame({ ...NEST, rim, halo, fill: base }).url};`);
  out.push(`  --ngn-${role}-hi: ${frame({ ...NEST, rim, halo, a: 1, b: 0.55, fill: [base, tint(halo, '.2')] }).url};`);
  out.push(`  --ngn-${role}-press: ${frame({ ...NEST, rim, halo, a: 1, b: 0.55, fill: [base, tint(halo, '.32')] }).url};`);
}
out.push(`  --ngn-dim: ${frame({ ...NEST, rim: 'rgba(180,228,238,.55)', halo: ROLES.cyan.halo, a: 0.4, b: 0.15, fill: FILL }).url};`);
out.push(`  --ngf-panel-slice: ${PANEL.o + PANEL.k}; --ngf-panel-out: ${PANEL.o}px; --ngh-panel-slice: 24;`);
out.push(`  --ngf-card-slice: ${CARD.o + CARD.k}; --ngf-card-out: ${CARD.o}px; --ngh-card-slice: 20;`);
out.push(`  --ngn-slice: ${NEST.o + NEST.k}; --ngn-out: ${NEST.o}px;`);
out.push(`  --ng-cut: ${PANEL.c}px; --ng-cut-card: ${CARD.c}px; --ng-cut-n: ${NEST.c}px;`);
out.push('}', '');
writeFileSync(new URL('../src/styles/neon-frames.css', import.meta.url), out.join('\n'));
console.log('wrote src/styles/neon-frames.css');
