import { appendFileSync, writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { LEGS } from '../src/content/road';
import { t } from '../src/i18n';
import { regionOf, sysById } from '../src/sim/chart';
import { endSortie, newJourney, plot, sortieDef, type Journey } from '../src/sim/journey';
import { World } from '../src/sim/world';
import { flyWorld, type Strategy } from './pilot';
import { planRoute } from './route';

// ── the road as a person plays it ────────────────────────────────────────
// `npm run pilot:person` flies the authored road, Cerro to the Threshold, the way a
// person might, and writes docs/BALANCE-PERSON.md. Unlike pilot:overhaul it says yes to
// every job and flies the job's goal (a race at full throttle, a drop through a gap in
// the sweep), mines a while before each gate, and counts the time spent reading the
// cards (they pause the world, so reading adds to the clock: 2 s to decide, and 230
// words a minute). Radio lines are read in flight and add nothing. Still a pilot: it
// does not explore, get lost or replay a fight, so a person will take longer.
// PERSON_RUNS sets the seeds; PERSON_LOG=path writes a line a stop.

const RUNS = Number(process.env.PERSON_RUNS ?? 3);
const STRAT: Strategy = { kind: 'focus', branch: 'torpedo', second: 'defence' };
const LOG = process.env.PERSON_LOG;
const LEG_NAMES = ['The Reach', 'The Marches', 'The Salvage Belt', 'The Drift Deep', 'The Breaker Yards', 'The Free Ports', 'The Hollows', 'The Last Lanes'];
const words = (s: string) => s.split(/\s+/).filter(Boolean).length;
interface CardLike { id: string; text?: string; title?: string; choices?: Array<{ label: string; hint?: string }> }
/** Seconds to read a card and pick an answer. */
const readSecs = (c: CardLike) => 2 + (words(t(c.text ?? '')) + words(t(c.title ?? '')) + (c.choices ?? []).reduce((a, ch) => a + words(t(ch.label)) + words(t(ch.hint ?? '')), 0)) / (230 / 60);

interface Out { reached: boolean; stuck: string | null; fly: number; read: number; leg: number[]; legRead: number[]; wrecks: number; cards: number; captains: number; jobs: Record<string, string> }

function fly(seed: number): Out {
  const j: Journey = newJourney(seed, false, 'road');
  const o: Out = { reached: false, stuck: null, fly: 0, read: 0, leg: LEGS.map(() => 0), legRead: LEGS.map(() => 0), wrecks: 0, cards: 0, captains: 0, jobs: {} };
  for (let n = 0; j.status !== 'over' && n < 90; n++) {
    if (j.status === 'chart') plot(j, planRoute(j));
    const def = sortieDef(j);
    const leg = Math.max(0, regionOf(sysById(j.chart, j.at)));
    const w = new World(seed * 31 + n * 7 + 1, { mode: 'breakout', sortie: def, carry: j.carry });
    const seen = new Set<string>();
    let read = 0;
    const offer = w.desk.offer.bind(w.desk) as (...a: unknown[]) => unknown;
    (w.desk as unknown as { offer: (...a: unknown[]) => unknown }).offer = (c: unknown, ...a: unknown[]) => {
      const card = c as CardLike;
      if (!seen.has(card.id)) { seen.add(card.id); read += readSecs(card); o.cards++; if (card.id.startsWith('captain:')) o.captains++; }
      return offer(c, ...a);
    };
    flyWorld(w, seed * 31 + n, STRAT, { maxTime: 1800, breakout: true, policy: 'take', chase: true, linger: { cyrite: 45, secs: 180 } });
    const gained = [...w.flags].filter((f) => /^job_.*_(won|lost|declined|ignored)$/.test(f) && !j.carry.flags.includes(f));
    for (const f of gained) { const m = /^job_(.*)_(won|lost|declined|ignored)$/.exec(f)!; o.jobs[m[1]!] = m[2]!; }
    if (LOG) appendFileSync(LOG, `${seed} #${n} ${def.script ?? def.name} fly=${Math.round(w.runTime)} read=${Math.round(read)} alive=${w.alive} cards=[${[...seen].join(' ')}] jobs=[${gained.join(' ')}] jobT=${Math.round(w.stage?.run?.clock ?? -1)}/${w.stage?.def.goal.limit ?? 0} lost=${w.run.platesLost} shields=${w.run.shieldsAbsorbed}\n`);
    if (w.phase !== 'over') { o.stuck = def.script ?? def.name; break; }
    o.fly += w.runTime; o.read += read; o.leg[leg]! += w.runTime + read; o.legRead[leg]! += read;
    if (!w.alive) o.wrecks++;
    endSortie(j, w.result());
  }
  o.reached = j.status === 'over' && j.end === 'through';
  return o;
}

const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const m = (s: number) => Math.round(s / 60);

it('flies the road as a person', { timeout: 14_400_000 }, () => {
  const all = Array.from({ length: RUNS }, (_, i) => ({ seed: 5000 + i * 17, ...fly(5000 + i * 17) }));
  const jobs = [...new Set(LEGS.flat().flatMap((s) => (s.job ? [s.job] : [])))];
  const md = `# The road as a person plays it

Generated by \`npm run pilot:person\`: the scripted pilot flew ${all.length} journeys down the authored road,
Cerro to the Threshold, the way a person might: it says yes to every job and flies its goal, mines a while
before each Jump Gate, and is charged for reading each card (2 s to decide, 230 words a minute; cards pause
the world). It does not explore, get lost or try a fight twice, so a person will take longer.
Pilot numbers, not playtests.

## Each journey

| Seed | Threshold | Flying (min) | Reading cards (min) | Total (min) | Cards | Named captains met | Wrecks |
|---|---|---|---|---|---|---|---|
${all.map((r) => `| ${r.seed} | ${r.reached ? 'yes' : r.stuck ? `stuck at ${r.stuck}` : 'no'} | ${m(r.fly)} | ${m(r.read)} | ${m(r.fly + r.read)} | ${r.cards} | ${r.captains} | ${r.wrecks} |`).join('\n')}

## Leg by leg (mean minutes, reading included)

| Leg | Minutes | Of which reading |
|---|---|---|
${LEG_NAMES.map((nm, i) => `| ${nm} | ${m(mean(all.map((r) => r.leg[i]!)))} | ${m(mean(all.map((r) => r.legRead[i]!)))} |`).join('\n')}

## Jobs, taken every time

| Job | Won | Lost | Other |
|---|---|---|---|
${jobs.map((id) => { const e = all.map((r) => r.jobs[id]); return `| ${id} | ${e.filter((x) => x === 'won').length} | ${e.filter((x) => x === 'lost').length} | ${e.filter((x) => x !== 'won' && x !== 'lost').length} |`; }).join('\n')}
`;
  writeFileSync(new URL('../docs/BALANCE-PERSON.md', import.meta.url), md);
});
